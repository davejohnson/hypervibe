import { spawn } from 'child_process';
import { redactSensitiveString } from '../../../utils/redact-sensitive-string.js';
import { OPENTOFU_VERSION } from './versions.js';

/**
 * Narrow OpenTofu process runner. It only exposes the commands Hypervibe's
 * lifecycle needs, runs them non-interactively in a caller-owned private
 * directory, enforces a timeout and cancellation, and redacts every supplied
 * secret value from captured output before it leaves this module.
 */
export type TofuCommand =
  | { kind: 'version' }
  | { kind: 'init' }
  | { kind: 'validate' }
  | { kind: 'plan'; out: string; destroy?: boolean }
  | { kind: 'apply'; planFile: string }
  | { kind: 'show-plan'; planFile: string }
  | { kind: 'show-state' }
  | { kind: 'output' };

export interface TofuRunOptions {
  binary: string;
  workingDirectory: string;
  /** Explicit process environment. The parent environment is NOT inherited. */
  env: Record<string, string>;
  /** Exact values (credentials, passphrases) that must never appear in output. */
  redact: string[];
  timeoutMs?: number;
  signal?: AbortSignal;
}

export interface TofuRunResult {
  exitCode: number | null;
  /** True when the process was stopped by timeout or cancellation. */
  interrupted: 'timeout' | 'cancelled' | undefined;
  stdout: string;
  stderr: string;
}

/** Variables passed from the parent process when present. Everything else is dropped. */
const INHERITED_ENV_KEYS = ['PATH', 'HOME', 'TMPDIR', 'LANG', 'SSL_CERT_FILE', 'SSL_CERT_DIR', 'HTTPS_PROXY', 'NO_PROXY'];

const MAX_CAPTURE_BYTES = 8 * 1024 * 1024;
const DEFAULT_TIMEOUT_MS = 30 * 60 * 1000;

export function tofuArguments(command: TofuCommand): string[] {
  switch (command.kind) {
    case 'version':
      return ['version', '-json'];
    case 'init':
      // The lock file is generated by Hypervibe from pinned checksums; never let init rewrite it.
      return ['init', '-input=false', '-no-color', '-lockfile=readonly'];
    case 'validate':
      return ['validate', '-json', '-no-color'];
    case 'plan':
      return [
        'plan', '-input=false', '-no-color', '-detailed-exitcode', '-lock-timeout=60s',
        `-out=${command.out}`, ...(command.destroy ? ['-destroy'] : []),
      ];
    case 'apply':
      // A saved plan carries its own approval; -auto-approve only suppresses the TTY prompt.
      return ['apply', '-input=false', '-no-color', '-json', '-lock-timeout=60s', '-auto-approve', command.planFile];
    case 'show-plan':
      return ['show', '-json', '-no-color', command.planFile];
    case 'show-state':
      return ['show', '-json', '-no-color'];
    case 'output':
      return ['output', '-json', '-no-color'];
  }
}

export function redactEngineOutput(text: string, exactValues: string[]): string {
  let result = text;
  const values = [...new Set(exactValues)].filter((value) => value.length >= 4).sort((a, b) => b.length - a.length);
  for (const value of values) {
    result = result.split(value).join('[redacted]');
    // Engines frequently JSON-escape values in diagnostics.
    const escaped = JSON.stringify(value).slice(1, -1);
    if (escaped !== value) result = result.split(escaped).join('[redacted]');
  }
  return redactSensitiveString(result);
}

export function engineProcessEnv(explicit: Record<string, string>, parent: NodeJS.ProcessEnv = process.env): Record<string, string> {
  const env: Record<string, string> = {};
  for (const key of INHERITED_ENV_KEYS) {
    const value = parent[key];
    if (value) env[key] = value;
  }
  return {
    ...env,
    TF_IN_AUTOMATION: '1',
    TF_INPUT: '0',
    CHECKPOINT_DISABLE: '1',
    ...explicit,
  };
}

export async function runTofu(command: TofuCommand, options: TofuRunOptions): Promise<TofuRunResult> {
  if (options.signal?.aborted) {
    return { exitCode: null, interrupted: 'cancelled', stdout: '', stderr: '' };
  }
  const child = spawn(options.binary, tofuArguments(command), {
    cwd: options.workingDirectory,
    env: engineProcessEnv(options.env),
    stdio: ['ignore', 'pipe', 'pipe'],
  });
  let stdout = '';
  let stderr = '';
  const append = (current: string, chunk: Buffer) =>
    current.length >= MAX_CAPTURE_BYTES ? current : current + chunk.toString('utf8');
  child.stdout.on('data', (chunk: Buffer) => { stdout = append(stdout, chunk); });
  child.stderr.on('data', (chunk: Buffer) => { stderr = append(stderr, chunk); });

  let interrupted: TofuRunResult['interrupted'];
  // SIGINT lets OpenTofu stop gracefully and persist state for in-flight work.
  const stop = (reason: 'timeout' | 'cancelled') => {
    if (interrupted) return;
    interrupted = reason;
    child.kill('SIGINT');
    setTimeout(() => { if (child.exitCode === null) child.kill('SIGKILL'); }, 60_000).unref();
  };
  const timer = setTimeout(() => stop('timeout'), options.timeoutMs ?? DEFAULT_TIMEOUT_MS);
  const onAbort = () => stop('cancelled');
  options.signal?.addEventListener('abort', onAbort, { once: true });

  const exitCode = await new Promise<number | null>((resolve, reject) => {
    child.once('error', reject);
    child.once('close', (code) => resolve(code));
  }).finally(() => {
    clearTimeout(timer);
    options.signal?.removeEventListener('abort', onAbort);
  });

  return {
    exitCode,
    interrupted,
    stdout: redactEngineOutput(stdout, options.redact),
    stderr: redactEngineOutput(stderr, options.redact),
  };
}

/** Confirms the binary is exactly the pinned release before any lifecycle use. */
export async function verifyEngineVersion(binary: string, workingDirectory: string): Promise<{ ok: true } | { ok: false; error: string }> {
  let result: TofuRunResult;
  try {
    result = await runTofu({ kind: 'version' }, { binary, workingDirectory, env: {}, redact: [], timeoutMs: 30_000 });
  } catch (error) {
    return { ok: false, error: `OpenTofu could not be started: ${error instanceof Error ? error.message : String(error)}` };
  }
  if (result.exitCode !== 0) return { ok: false, error: 'OpenTofu version check failed.' };
  try {
    const parsed = JSON.parse(result.stdout) as { terraform_version?: string };
    if (parsed.terraform_version !== OPENTOFU_VERSION) {
      return { ok: false, error: `OpenTofu ${parsed.terraform_version ?? 'unknown'} is installed; Hypervibe requires exactly ${OPENTOFU_VERSION}.` };
    }
    return { ok: true };
  } catch {
    return { ok: false, error: 'OpenTofu version output was not machine-readable.' };
  }
}
