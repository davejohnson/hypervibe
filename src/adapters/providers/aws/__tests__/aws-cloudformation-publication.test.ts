import { describe, expect, it, vi } from 'vitest';
import { createAwsCloudInstallationDriver, createAwsCloudInstallationTemplateV1 } from '../aws-cloud-installation.js';
import { createAwsCloudDeploymentTemplateV1 } from '../aws-cloud-deployment.js';
import type { CloudInstallationIntent, CloudInstallationProviderContext } from '../../../../domain/ports/cloud-installation.port.js';

// Reconstructed S3 HTTP responses through the real collection/deployment drivers.
// CFN TemplateURL permits S3 REST objects, not arbitrary HTTPS/static websites:
// https://docs.aws.amazon.com/AWSCloudFormation/latest/APIReference/API_CreateStack.html
// S3 explicitly permits overwriting the null version; its presence is not immutability:
// https://docs.aws.amazon.com/AmazonS3/latest/userguide/AddingObjectstoVersionSuspendedBuckets.html
// GetObject documents x-amz-version-id and URL-encoded opaque version IDs:
// https://docs.aws.amazon.com/AmazonS3/latest/API/API_GetObject.html
// Console template URLs are limited to 1,024 characters (unlike the wider API limit):
// https://docs.aws.amazon.com/AWSCloudFormation/latest/UserGuide/cfn-console-create-stack.html
const intent: CloudInstallationIntent = { schemaVersion: 1, installationId: 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa',
  customerId: 'customer', appId: 'app', environment: 'production', provider: 'aws', mode: 'connect', keys: ['API_KEY'],
  nativeScope: { accountId: '123456789012', region: 'us-west-2' },
  source: { repository: 'github.com/example/app', branch: 'main', revision: 'a'.repeat(40), specDigest: 'b'.repeat(64) },
  hostIdentity: { kind: 'gcp-service-account', projectId: 'hosting-project', projectNumber: '123456789',
    serviceAccountEmail: 'delivery@hosting-project.iam.gserviceaccount.com', subject: '123456789012345678901', issuer: 'https://accounts.google.com' } };
const version = '3/L4kqtJlcpXroDTDmJ+rmSpXd3QBpUMLUo';
function fixture(deployment: boolean) {
  const artifact = deployment ? createAwsCloudDeploymentTemplateV1() : createAwsCloudInstallationTemplateV1();
  const url = `https://hypervibe-templates.s3.us-west-2.amazonaws.com/releases/${artifact.sha256}.json?versionId=${encodeURIComponent(version)}`;
  const ctx: CloudInstallationProviderContext = { intent: deployment ? { ...intent, purpose: 'deployment', stage: 'deployment', keys: [],
    deployment: { hostingProvider: 'ecs', region: 'us-west-2', workloads: [{ name: 'web', kind: 'web', runtimeSecrets: [] }] } } : intent,
    signal: new AbortController().signal, completed: {}, beforeMutation: vi.fn(async () => {}),
    authentication: { host: { verifyIdentity: async () => intent.hostIdentity, getIdToken: async () => { throw new Error('No federation before install'); },
      getAccessToken: async () => { throw new Error('No admin token'); } } } };
  const response = (body: ConstructorParameters<typeof Response>[0] = artifact.body, responseUrl = url, header: string | null = version) => {
    const result = new Response(body, { headers: header === null ? {} : { 'x-amz-version-id': header } });
    Object.defineProperty(result, 'url', { value: responseUrl }); return result;
  };
  const driver = (templateUrl = url, fetch: typeof globalThis.fetch = async () => response()) => createAwsCloudInstallationDriver({
    [deployment ? 'deploymentTemplateUrl' : 'templateUrl']: templateUrl, fetch,
  });
  return { artifact, url, ctx, response, driver };
}

describe.each([false, true])('AWS S3 template publication (deployment=%s)', deployment => {
  it.each(['https-host', 'website', 'null-version', 'duplicate-version', 'dotted-bucket', 'console-too-long'] as const)('rejects %s before fetching or handing off installation', async mode => {
    const f = fixture(deployment);
    const invalid = mode === 'https-host' ? f.url.replace('hypervibe-templates.s3.us-west-2.amazonaws.com', 'templates.hypervibe.dev')
      : mode === 'website' ? f.url.replace('.s3.us-west-2.', '.s3-website-us-west-2.')
      : mode === 'null-version' ? f.url.replace(/versionId=.+/, 'versionId=null')
      : mode === 'duplicate-version' ? f.url + '&versionId=another'
      : mode === 'console-too-long' ? f.url.replace('/releases/', `/${'a'.repeat(900)}/`)
      : f.url.replace('hypervibe-templates.s3.', 'hypervibe.templates.s3.');
    const fetch = vi.fn(async () => f.response()), driver = f.driver(invalid, fetch);
    await expect(driver.plan(f.ctx)).rejects.toThrow(); expect(fetch).not.toHaveBeenCalled();
    const action = (await f.driver().plan(f.ctx)).actions[0];
    await expect(driver.mutate({ ...f.ctx, action, attempt: { id: 'bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb', actionId: action.id,
      status: 'attempted', startedAt: '2026-10-25T00:00:00Z', updatedAt: '2026-10-25T00:00:00Z' } })).rejects.toThrow();
    expect(fetch).not.toHaveBeenCalled(); expect(f.ctx.beforeMutation).not.toHaveBeenCalled();
  });
  it('verifies the exact S3 version and generated bytes before issuing the console URL', async () => {
    const f = fixture(deployment), fetch = vi.fn(async () => f.response()), driver = f.driver(f.url, fetch);
    const action = (await driver.plan(f.ctx)).actions[0];
    const result = await driver.mutate({ ...f.ctx, action, attempt: { id: 'bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb', actionId: action.id,
      status: 'attempted', startedAt: '2026-10-25T00:00:00Z', updatedAt: '2026-10-25T00:00:00Z' } });
    expect(result.state).toBe('external'); if (result.state !== 'external') return;
    expect(new URLSearchParams(new URL(result.url).hash.split('?')[1]).get('templateURL')).toBe(f.url);
    expect(fetch).toHaveBeenCalledTimes(2);
    expect(fetch).toHaveBeenLastCalledWith(f.url, expect.objectContaining({ redirect: 'error', signal: expect.any(AbortSignal) }));
  });
  it.each(['missing-version', 'wrong-version', 'wrong-url', 'redirect', 'changed-bytes', 'oversize'] as const)('rejects %s response evidence', async mode => {
    const f = fixture(deployment), response = f.response(mode === 'changed-bytes' ? '{}' : mode === 'oversize' ? 'x'.repeat(1_048_577) : f.artifact.body,
      mode === 'wrong-url' ? f.url.replace('hypervibe-templates', 'another-bucket') : f.url,
      mode === 'missing-version' ? null : mode === 'wrong-version' ? 'other-version' : version);
    if (mode === 'redirect') Object.defineProperty(response, 'redirected', { value: true });
    await expect(f.driver(f.url, async () => response).plan(f.ctx)).rejects.toThrow();
    expect(f.ctx.beforeMutation).not.toHaveBeenCalled();
  });
  it('bounds response body completion and cancels it without replay', async () => {
    vi.useFakeTimers();
    try {
      const f = fixture(deployment), cancel = vi.fn(), fetch = vi.fn(async () => f.response(new ReadableStream({ cancel })));
      const outcome = f.driver(f.url, fetch).plan(f.ctx).then(() => 'unexpected', () => 'blocked');
      await vi.advanceTimersByTimeAsync(15_001); expect(await outcome).toBe('blocked');
      expect(fetch).toHaveBeenCalledOnce(); expect(cancel).toHaveBeenCalledOnce();
    } finally { vi.useRealTimers(); }
  });
});
