type Promotion = Exclude<ReturnType<typeof buildGcpPromotionWorkflow>, { blocked: string }>;

/** Both command entry points use the same reviewed file, applied target and repository connection. */
async function installedPromotion(project: Project, spec: ProjectSpec, environment: Environment) {
  const expected = buildGcpPromotionWorkflow(project, spec, environment);
  if ('blocked' in expected) throw new Error(expected.blocked);
  const repository = parseGitHubRepoFromRemote(project.gitRemoteUrl);
  if (!repository || repository.toLowerCase() !== expected.repository.toLowerCase()) {
    throw new Error('The promotion repository differs from the applied environment.');
  }
  const github = getGitHubAdapter(repository);
  if ('error' in github) throw new Error(github.error);
  const [owner, repo] = repository.split('/') as [string, string];
  const { adapter } = github;
  const [identity, definition, ref] = await Promise.all([
    adapter.getRepository(owner, repo), adapter.getWorkflow(owner, repo, expected.path),
    adapter.getRef(owner, repo, 'heads/' + expected.branch),
  ]);
  const head = releaseSource.trustedReleaseHead(ref, expected.branch);
  if (identity.full_name?.toLowerCase() !== repository.toLowerCase() || !Number.isSafeInteger(identity.id) || String(identity.id) !== expected.repositoryId
    || identity.default_branch !== expected.branch
    || definition.path !== expected.path || definition.state !== 'active' || !Number.isSafeInteger(definition.id) || definition.id < 1) {
    throw new Error('GitHub could not verify the active promotion workflow in the applied repository.');
  }
  if (await adapter.getFileContent(owner, repo, expected.path, head) !== expected.content) {
    throw new Error('Publish the promotion workflow generated by hv_launch to ' + expected.branch + ' before promoting.');
  }
  return { expected, owner, repo, adapter, head, definition, repositoryId: identity.id };
}

export async function dispatchEnginePromotion(ctx: CommandContext, project: Project, spec: ProjectSpec, environment: Environment,
  selection: { ref?: string; sha?: string; inputs?: Record<string, string>; definitionId?: number } = {}) {
  const pending = pendingCredentialUpdate(project.id);
  if (pending) throw new Error('Finish the pending credential update through hv_apply before promoting.');
  const { expected, owner, repo, adapter, head, definition } = await installedPromotion(project, spec, environment);
  if (selection.ref !== undefined && selection.ref !== expected.branch || selection.sha !== undefined && selection.sha !== head
    || selection.definitionId !== undefined && selection.definitionId !== definition.id || Object.keys(selection.inputs ?? {}).length) {
    throw new Error('Promotion takes the whole verified staging release on the configured branch and accepts no overrides.');
  }
  if (releaseSource.trustedReleaseHead(await adapter.getRef(owner, repo, 'heads/' + expected.branch), expected.branch) !== head) {
    throw new Error('The promotion branch moved during review. Review the current workflow again.');
  }
  try {
    await adapter.triggerWorkflow(owner, repo, String(definition.id), expected.branch);
  } catch {
    throw new Error('The promotion dispatch could not be confirmed. Check hv_ci_status for this workflow before retrying.');
  }
  ctx.repos.audit.create({ action: 'hv.ci_trigger', resourceType: 'github_workflow', resourceId: expected.repository + '/' + definition.id,
    details: { workflow: expected.path, ref: expected.branch, environment: environment.name, sourceEnvironment: expected.sourceEnvironment, reviewedSha: head } });
  return { status: 'pending' as const, repository: expected.repository, workflow: expected.path, ref: expected.branch,
    environment: environment.name, sourceEnvironment: expected.sourceEnvironment };
}

/** GitHub accepts workflow file names and numeric IDs. Resolve aliases before they can take the generic dispatch path. */
export async function dispatchIfEnginePromotion(ctx: CommandContext, project: Project, selection: {
  definition: string; repo?: string; ref?: string; sha?: string; inputs?: Record<string, string>;
}) {
  const spec = new SpecStore().get(project)?.spec;
  if (!spec) return;
  const targets = Object.entries(spec.environments).filter(([, env]) => isEngineManaged(env) && env.deploy?.promoteFrom);
  if (!targets.length) return;
  const file = (name: string) => '.github/workflows/hypervibe-release-' + name + '.yml';
  let selected = targets.find(([name]) => [file(name), file(name).split('/').at(-1)].includes(selection.definition));
  let definitionId: number | undefined;
  if (!selected) {
    const repository = selection.repo ?? parseGitHubRepoFromRemote(project.gitRemoteUrl);
    if (!repository) throw new Error('The workflow repository is unknown.');
    const github = getGitHubAdapter(repository);
    if ('error' in github) throw new Error(github.error);
    const [owner, repo] = repository.split('/');
    const actual = await github.adapter.getWorkflow(owner!, repo!, selection.definition);
    selected = targets.find(([name]) => file(name) === actual.path);
    if (!selected) return;
    definitionId = actual.id;
  }
  if (selection.repo && selection.repo.toLowerCase() !== parseGitHubRepoFromRemote(project.gitRemoteUrl)?.toLowerCase()) {
    throw new Error('Use the repository bound to the target for promotion.');
  }
  const environment = ctx.repos.environments.findByProjectAndName(project.id, selected[0]);
  if (!environment) throw new Error('Apply the target environment before promoting.');
  return dispatchEnginePromotion(ctx, project, spec, environment, { ...selection, definitionId });
}

const positive = z.number().int().positive().safe();
const sha = z.string().regex(/^[0-9a-f]{40}$/);
const promotionReceipt = z.object({
  version: z.literal(1), repository: z.string(), environment: z.string(), workflowSha: sha,
  runId: positive, runAttempt: positive, gcpProjectId: z.string(), region: z.string(),
  source: z.object({ environment: z.string(), sha, runId: positive, runAttempt: positive, artifactId: positive }),
  services: z.array(z.object({ name: z.string(), resource: z.string(), kind: z.enum(['services', 'workerPools', 'jobs']),
    image: z.string().regex(/^[^\s@]+@sha256:[0-9a-f]{64}$/), uid: z.string().min(1) })).min(1),
});

async function verifyPromotedWorkloads(token: string, expected: Promotion, receipt: z.infer<typeof promotionReceipt>) {
  if (receipt.services.length !== expected.services.length || new Set(receipt.services.map(s => s.name)).size !== receipt.services.length) {
    throw new Error('The promoted release covers a different set of workloads.');
  }
  const results: EngineReleaseResult[] = [];
  for (const service of expected.services) {
    const item = receipt.services.find(s => s.name === service.name);
    if (!item || item.kind !== service.kind || item.resource !== service.resource || item.uid !== service.uid || item.image.split('@')[0] !== service.image) {
      throw new Error('The promotion receipt names a different target for ' + service.name + '.');
    }
    const live = await cloudRunGet(token, expected.gcpProjectId, expected.region, item.resource, item.kind);
    const resource = 'projects/' + expected.gcpProjectId + '/locations/' + expected.region + '/' + item.kind + '/' + item.resource;
    if (live.state !== 'present' || live.value.name !== resource || live.value.uid !== item.uid || live.value.deleteTime) {
      throw new Error('Google Cloud could not confirm the ready promoted workload ' + service.name + '.');
    }
    assertGcpPromotionWorkloadReady(live.value, item.kind);
    const containers = workloadContainers(item.kind, live.value);
    if (containers.length !== 1 || containers[0]?.image !== item.image) throw new Error(service.name + ' is no longer on the promoted image.');
    const url = item.kind === 'services' && live.value.uri ? normalizedTrafficOrigin('', live.value.uri) : undefined;
    results.push({ service: service.name, status: 'released', imageUri: item.image, ...(url && { url }),
      message: 'Google Cloud is running the verified staging image.' });
  }
  return results;
}

/** A spec flag alone cannot qualify a target for a cutover or make launch report it live. */
export async function observeEnginePromotion(ctx: CommandContext, project: Project, spec: ProjectSpec, environment: Environment):
Promise<{ results: EngineReleaseResult[] } | { blocked: string }> {
  try {
    const { expected, adapter, owner, repo, head, repositoryId, definition } = await installedPromotion(project, spec, environment);
    const history = () => rollbackHistory(adapter, owner, repo, String(definition.id));
    const latest = (await history())[0];
    if (!latest || latest.status !== 'completed' || latest.conclusion !== 'success') throw new Error('A successful current promotion has not been verified.');
    const run = await adapter.getWorkflowRun(owner, repo, latest.id);
    if (run.id !== latest.id || run.run_attempt !== latest.run_attempt || run.head_sha !== latest.head_sha
      || run.event !== 'workflow_dispatch' || run.repository?.id !== repositoryId
      || !await releaseSource.isCommitOnReleaseBranch(run.head_sha, head, (base, tip) => adapter.compareCommits(owner, repo, base, tip))
      || await adapter.getFileContent(owner, repo, expected.path, run.head_sha) !== expected.content) {
      throw new Error('The successful run used a different promotion workflow or target.');
    }
    const [artifacts, jobs] = await Promise.all([adapter.listWorkflowRunArtifacts(owner, repo, run.id),
      adapter.listWorkflowRunAttemptJobs(owner, repo, run.id, run.run_attempt)]);
    const name = 'hypervibe-gcp-promotion-v1-' + run.id + '-' + run.run_attempt;
    const matches = artifacts.artifacts.filter(a => a.name === name);
    if (artifacts.total_count !== artifacts.artifacts.length || matches.length !== 1
      || !releaseSource.matchesReleaseProducer(run, matches[0], expected.repository, expected.branch, expected.path)) {
      throw new Error('The current promotion has no unique verified release receipt.');
    }
    const artifact = matches[0]!;
    assertCurrentReleaseAttempt(run, artifact, jobs, 'release');
    const parsed = promotionReceipt.safeParse(await adapter.readJsonArtifact(owner, repo, artifact.id, 'promotion.json'));
    if (!parsed.success) throw new Error('The promotion receipt is incomplete.');
    const r = parsed.data;
    if (r.repository.toLowerCase() !== expected.repository.toLowerCase() || r.environment !== environment.name || r.workflowSha !== run.head_sha
      || r.runId !== run.id || r.runAttempt !== run.run_attempt || r.gcpProjectId !== expected.gcpProjectId
      || r.region !== expected.region || r.source.environment !== expected.sourceEnvironment) throw new Error('The promotion receipt belongs to another release.');
    const context = await resolveEngineContext(ctx, project, spec, environment.name);
    if ('blocked' in context || context.gcpProjectId !== expected.gcpProjectId || context.region !== expected.region) {
      throw new Error('The applied Google Cloud target could not be verified.');
    }
    const results = await verifyPromotedWorkloads(await context.adapter.engineAccessToken(), expected, r);
    assertSameReleaseAttempt(run, await adapter.getWorkflowRun(owner, repo, run.id), 'refs/heads/' + expected.branch);
    const now = (await history())[0];
    if (now?.id !== run.id || now.run_attempt !== run.run_attempt || now.status !== 'completed' || now.conclusion !== 'success') {
      throw new Error('The production promotion changed during verification.');
    }
    return { results };
  } catch (error) {
    const message = error instanceof Error ? error.message : 'Release evidence is unavailable.';
    return { blocked: 'Promotion from ' + spec.environments[environment.name]?.deploy?.promoteFrom + ' could not be verified. ' + message
      + ' Check hv_ci_status. Use hv_deploy to promote once the workflow is ready.' };
  }
}
