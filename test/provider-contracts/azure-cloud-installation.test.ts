it('recovers a historical migrated writer and verifies its remaining trust without changing the existing vault', async () => {
  const f = fixture(), legacyVault = `${group}/providers/Microsoft.KeyVault/vaults/legacy-app-vault`;
  const destination = { provider: 'azure-key-vault' as const, tenantId, subscriptionId, resourceGroup: 'sequence-staging', vaultName: 'legacy-app-vault', secretName: 'preserved-key-name' };
  const migration = { ...intent, mode: 'migrate' as const, migrationTargets: [{ key: 'API_TOKEN', destination }] };
  const existing = { ...structuredClone(nativeResources[vault]), id: legacyVault, name: 'legacy-app-vault', tags: { owner: 'customer',...vaultOwnership },
    properties: { ...nativeResources[vault].properties, vaultUri: 'https://legacy-app-vault.vault.azure.net/', softDeleteRetentionInDays: 30, enablePurgeProtection: false } };
  f.responses.set(legacyVault, existing);
  // Migration needs no permission to update the retained vault.
  f.responses.set(`${group}/providers/Microsoft.Authorization/permissions`, { value: [{ actions: [
    'Microsoft.ManagedIdentity/userAssignedIdentities/write', 'Microsoft.ManagedIdentity/userAssignedIdentities/federatedIdentityCredentials/write',
    'Microsoft.Resources/deployments/write', 'Microsoft.Resources/deployments/read', 'Microsoft.Resources/deployments/operations/read',
    'Microsoft.Authorization/roleDefinitions/write', 'Microsoft.Authorization/roleAssignments/write'], notActions: [] }] });
  const context = { ...f.context, intent: migration }, plan = await f.driver.plan(context);
  // Historical records predate the new reviewed namespace/deployment contract.
  // Preserve their read-only recovery and exact trust handling.
  for (const action of plan.actions) { delete action.metadata.native.lifecycle; action.verified = action.type === 'noop' && action.id !== 'azure:verify'; }
  for (const action of plan.actions) {
    let observed = await f.driver.inspect({ ...context, action });
    if (observed.state === 'action-required') {
      const kind = String(action.metadata.native.kind), id = String(action.metadata.native.resourceId);
      const nativeId = kind === 'writer' ? writer : kind === 'role' ? role : kind === 'federation' ? federation : grant;
      const resource = structuredClone(nativeResources[nativeId]); resource.id = id;
      if (kind === 'grant') resource.properties.scope = legacyVault;
      if(kind==='writer')f.responses.set(id,resource);
      else{f.writeResponses.set(id, resource);
        expect(await f.driver.mutate({ ...context, action, attempt: attempt(action) })).toMatchObject({ state: 'acknowledged' });}
      observed = await f.driver.recover({ ...context, action, attempt: attempt(action) });
    }
    expect(observed).toMatchObject({ state: 'satisfied' });
    if (observed.state === 'satisfied') context.completed![action.id] = observed.evidence;
  }
  const record = { schemaVersion: 1 as const, installationId: migration.installationId, revision: 1, intent: migration,
    plan: { digest: 'a'.repeat(64), ...plan }, status: 'ready' as const, attempts: [], completed: context.completed! };
  expect(f.driver.connections(record)).toMatchObject([{ key: 'API_TOKEN', destination }]);
  expect(f.responses.get(legacyVault)).toEqual(existing);
  expect(f.events.filter(event => event.method === 'PUT').map(event => new URL(event.url).pathname)).toEqual([
    role, federation, `${legacyVault}/providers/Microsoft.Authorization/roleAssignments/4632693b-185f-5b24-8241-49de864f54dd`]);
});

