#!/usr/bin/env node
// Generates docs/TOOLS.md from the transport-neutral command registry.
// MCP registrations and CLI routes are both derived from this source.
import fs from 'node:fs';
import path from 'node:path';
import { mkdtempSync } from 'node:fs';
import os from 'node:os';

const repoRoot = process.cwd();
const outputPath = path.join(repoRoot, 'docs', 'TOOLS.md');
const registryModule = path.join(repoRoot, 'dist', 'application', 'commands.js');

if (!fs.existsSync(registryModule)) {
  console.error('dist/application/commands.js not found — run `npm run build` first.');
  process.exit(1);
}

// Point the sqlite store at a throwaway directory so doc generation never
// touches real state.
process.env.HYPERVIBE_DATA_DIR = mkdtempSync(path.join(os.tmpdir(), 'hypervibe-docs-'));

await import(path.join(repoRoot, 'dist', 'application', 'providers.js'));
const { initializeDatabase } = await import(path.join(repoRoot, 'dist', 'adapters', 'db', 'sqlite.adapter.js'));
const { createCommandContext } = await import(path.join(repoRoot, 'dist', 'application', 'context.js'));
const { createCommandRegistry } = await import(registryModule);
initializeDatabase();
const commands = createCommandRegistry(createCommandContext()).list();
commands.sort((a, b) => a.id.localeCompare(b.id));

const groups = new Map([
  ['Core (spec → plan → apply)', /^hv_(spec$|plan$|apply$|status$|inspect$|import$|destroy$)/],
  ['Connections', /^hv_connections/],
  ['Deploy & observability', /^hv_(deploy|rollback|logs|health)$/],
  ['Database', /^hv_db_/],
  ['Secrets', /^hv_secrets$/],
  ['CI', /^hv_ci_/],
  ['App Store & iOS', /^hv_appstore_/],
  ['Developer experience', /^hv_runs$/],
]);

let md = '';
md += '# Command Catalog\n\n';
md += 'Generated from the shared command registry.\n\n';
md += `Total commands: **${commands.length}** (available through both MCP and CLI)\n\n`;
md += '_Do not edit this file manually. Re-generate with `npm run build && npm run docs:tools`._\n\n';

const seen = new Set();
for (const [heading, pattern] of groups) {
  const matched = commands.filter((command) => pattern.test(command.id) && !seen.has(command.id));
  if (matched.length === 0) continue;
  md += `## ${heading}\n\n`;
  for (const command of matched) {
    seen.add(command.id);
    const description = command.description.split('\n')[0];
    md += `- \`${command.id}\` / \`hypervibe ${command.cliPath.join(' ')}\` - ${description}\n`;
  }
  md += '\n';
}

const ungrouped = commands.filter((command) => !seen.has(command.id));
if (ungrouped.length > 0) {
  md += '## Other\n\n';
  for (const command of ungrouped) {
    md += `- \`${command.id}\` / \`hypervibe ${command.cliPath.join(' ')}\` - ${command.description.split('\n')[0]}\n`;
  }
  md += '\n';
}

fs.writeFileSync(outputPath, md, 'utf8');
console.log(`Wrote ${outputPath} (${commands.length} commands)`);
process.exit(0);
